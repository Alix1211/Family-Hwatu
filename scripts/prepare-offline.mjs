import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';

const output = resolve(import.meta.dirname, '../dist-offline');

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  }));
  return files.flat();
}

const files = (await listFiles(output))
  .map(path => relative(output, path).split(sep).join('/'))
  .filter(path => path !== 'service-worker.js');
if (!files.includes('index.html')) throw new Error('Offline build has no index.html');

const manifestPath = join(output, 'manifest.webmanifest');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
manifest.name = 'Family Hwatu Offline';
manifest.short_name = 'Family Hwatu';
manifest.description = '서버 없이 AI와 즐기는 개인용 맞고·고스톱';
manifest.start_url = './#/home';
manifest.scope = './';
for (const icon of manifest.icons ?? []) icon.src = `.${icon.src}`;
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const precache = files.map(path => `./${path}`);
const worker = `// Generated by scripts/prepare-offline.mjs; all app assets are cached after first install.
const CACHE_NAME = 'family-hwatu-offline-v1';
const PRECACHE = ${JSON.stringify(precache)};
const ROOT = new URL('./', self.registration.scope);
const SHELL = new URL('index.html', ROOT);
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    for (let index = 0; index < PRECACHE.length; index += 30) {
      await cache.addAll(PRECACHE.slice(index, index + 30));
    }
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name !== CACHE_NAME && name.startsWith('family-hwatu-offline-')).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== ROOT.origin || !url.pathname.startsWith(ROOT.pathname)) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match(SHELL)));
    return;
  }
  event.respondWith(caches.match(request).then(cached => cached ?? fetch(request).then(response => {
    if (response.ok) void caches.open(CACHE_NAME).then(cache => cache.put(request, response.clone()));
    return response;
  })));
});
`;
await writeFile(join(output, 'service-worker.js'), worker);
console.log(`Offline PWA prepared: ${files.length} static files cached on first install`);
